param(
    [Parameter(Mandatory = $true)]
    [string]$BackendOrigin
)

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$frontendRoot = Join-Path $projectRoot 'frontend'

try { $backendUri = [Uri]::new($BackendOrigin.TrimEnd('/')) }
catch { throw 'BackendOrigin must be an HTTPS origin, for example https://machine.tailnet.ts.net.' }

if (-not $backendUri.IsAbsoluteUri -or $backendUri.Scheme -ne 'https' -or
    $backendUri.UserInfo -or $backendUri.Query -or $backendUri.Fragment -or
    $backendUri.AbsolutePath -ne '/') {
    throw 'BackendOrigin must contain only an HTTPS origin, without a path, query, fragment or credentials.'
}

$backendBase = $backendUri.GetLeftPart([System.UriPartial]::Authority)
$webSocketOrigin = 'wss://' + $backendUri.Authority
$contentSecurityPolicy = "default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data: blob:; connect-src 'self' $webSocketOrigin; media-src 'self' blob:; object-src 'none'; frame-ancestors 'none'; base-uri 'self'; form-action 'self'"

$config = [ordered]@{
    '$schema' = 'https://openapi.vercel.sh/vercel.json'
    rewrites = @(
        @{ source = '/api'; destination = "$backendBase/api" }
        @{ source = '/api/:path*'; destination = "$backendBase/api/:path*" }
        @{ source = '/assets/:path*'; destination = '/:path*' }
    )
    headers = @(
        @{
            source = '/(.*)'
            headers = @(
                @{ key = 'Content-Security-Policy'; value = $contentSecurityPolicy }
                @{ key = 'Permissions-Policy'; value = 'camera=(self), microphone=(self), geolocation=()' }
                @{ key = 'Referrer-Policy'; value = 'same-origin' }
                @{ key = 'Strict-Transport-Security'; value = 'max-age=31536000' }
                @{ key = 'X-Content-Type-Options'; value = 'nosniff' }
                @{ key = 'X-Frame-Options'; value = 'DENY' }
            )
        }
    )
}

$utf8NoBom = [System.Text.UTF8Encoding]::new($false)
$vercelPath = Join-Path $frontendRoot 'vercel.json'
$jsOrigin = ConvertTo-Json -InputObject $backendBase -Compress
$jsConfig = "// Generated by deploy/prepare-vercel.ps1.`nwindow.INTERVIEWACE_BACKEND_WS_ORIGIN = $jsOrigin;`n"
[System.IO.File]::WriteAllText($vercelPath, (($config | ConvertTo-Json -Depth 8) + [Environment]::NewLine), $utf8NoBom)
[System.IO.File]::WriteAllText((Join-Path $frontendRoot 'deploy-config.js'), $jsConfig, $utf8NoBom)

Write-Output 'Created frontend/vercel.json and frontend/deploy-config.js.'
Write-Output 'Review and commit these two deployment files before deploying the frontend root to Vercel.'
